#Requires -Version 7
# Writes docs\PROJECT-TREE.generated.md: the source tree as a table (every folder under src\, samples\, tools\, installer\
# and docs\ with its files, lines of code and a one-line purpose from the folder's README or first file comment). The
# project PDF (docs\guide\guide-project.txt) includes it, so the published tree never lags the repository. Generated;
# never edit by hand. Usage: .\tools\write-tree.ps1
param([switch]$Settled)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root
$enc = New-Object Text.UTF8Encoding $false
# Only files git tracks are counted (ADR-123): the table is the same in every clone, whatever lies around untracked.
$tracked = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
foreach ($t in (& git -C $root -c core.quotepath=off ls-files)) { [void]$tracked.Add((Join-Path $root ($t -replace '/', '\'))) }
if ($tracked.Count -lt 100) { throw 'git ls-files listed almost nothing - is this the repository root?' }
$skip = '\\(bin|obj|\.vs|publish|dist|node_modules|\.git)(\\|$)'
$codeExt = '.cs', '.xaml', '.ps1', '.md', '.json', '.wxs', '.html', '.js', '.css', '.txt', '.props', '.csproj', '.sln', '.xml'

function Lines([IO.FileInfo]$f) {
    if ($f.Extension -notin $codeExt -or $f.Length -gt 3MB) { return 0 }
    try { return ([IO.File]::ReadAllLines($f.FullName)).Count } catch { return 0 }
}

$rows = New-Object System.Collections.Generic.List[string]
$totalFiles = 0; $totalLines = 0; $csLines = 0
foreach ($top in 'src', 'samples', 'tools', 'installer', 'docs') {
    if (-not (Test-Path $top)) { continue }
    $dirs = @(Get-Item $top) + @(Get-ChildItem $top -Directory -Recurse | Where-Object { $_.FullName -notmatch $skip })
    foreach ($d in ($dirs | Sort-Object FullName)) {
        $files = @(Get-ChildItem $d.FullName -File | Where-Object { $_.Name -notlike '*_wpftmp.csproj' -and $_.Name -ne 'packages.lock.json' -and $tracked.Contains($_.FullName) })
        if ($files.Count -eq 0) { continue }
        $lines = 0; foreach ($f in $files) { $n = Lines $f; $lines += $n; if ($f.Extension -eq '.cs') { $csLines += $n } }
        $totalFiles += $files.Count; $totalLines += $lines
        $rel = $d.FullName.Substring($root.Length + 1)
        # The purpose: the folder's README's first paragraph, else the first XML doc summary / comment line of its first .cs file.
        $purpose = ''
        $readme = Join-Path $d.FullName 'README.md'
        if (Test-Path $readme) {
            $purpose = ((Get-Content $readme -Encoding UTF8 | Where-Object { $_ -and $_ -notmatch '^#' } | Select-Object -First 1) -replace '\|', '/').Trim()
        }
        if (-not $purpose) {
            $first = $files | Where-Object Extension -eq '.cs' | Sort-Object Name | Select-Object -First 1
            if ($first) {
                $text = [IO.File]::ReadAllLines($first.FullName) | Where-Object { $_ -match '^\s*///\s*(?!<summary>|</summary>)\S|^\s*//\s*\S' } | Select-Object -First 1
                if ($text) { $purpose = ($text -replace '^\s*///?\s*', '' -replace '<[^>]+>', '' -replace '\|', '/').Trim(); if ($purpose.Length -gt 160) { $purpose = $purpose.Substring(0, 157) + '…' } }
            }
        }
        # Markdown-safe cells: emphasis characters in a comment are escaped (an unbalanced run would nest the whole table),
        # and the file list is cut between names, never inside a code span.
        $purpose = $purpose -replace '([*_~<>\[\]\\])', '\$1'
        $sorted = @($files | Sort-Object Name | ForEach-Object { '`' + $_.Name + '`' })
        $names = ($sorted | Select-Object -First 40) -join ', '
        if ($sorted.Count -gt 40) { $names += " … (+$($sorted.Count - 40) more)" }
        $rows.Add("| ``$rel`` | $($files.Count) | $lines | $purpose | $names |")
    }
}
$out = @"
# Project tree (generated $(Get-Date -Format 'yyyy-MM-dd'))

Every folder of the repository that holds files, with its file count, lines (source, markup, scripts and docs) and purpose.
Build output (``bin``, ``obj``, ``publish``), release folders (``dist``) and tool caches are not part of the source tree.
Generated by ``tools\write-tree.ps1``; the structure and how it is built out are explained in PROJECT-TREE.md.

**Totals:** $totalFiles files · $('{0:N0}' -f $totalLines) lines, of which $('{0:N0}' -f $csLines) lines of C#.

| Folder | Files | Lines | Purpose | Files |
|---|---|---|---|---|
$($rows -join "`n")
"@
[IO.File]::WriteAllText((Join-Path $root 'docs\PROJECT-TREE.generated.md'), $out, $enc)
Write-Host "docs\PROJECT-TREE.generated.md: $($rows.Count) folders, $totalFiles files, $('{0:N0}' -f $totalLines) lines"
# The table counts its own lines too, so one pass can change the count it just wrote: a second pass settles it (the
# row count, and so the file's own line count, doesn't change). build.ps1 compares the result with the commit.
if (-not $Settled) { & $PSCommandPath -Settled }
