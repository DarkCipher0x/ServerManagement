using System.Text;
using System.Text.RegularExpressions;
using DcxManager.Net;
using DcxManager.Services;

namespace DcxManager.Ansible;

/// <summary>
/// An Ansible inventory (YAML) generated from saved hosts (0.3.0 §16): every SSH host with ansible_host / port / user,
/// grouped by its folder path (Production/EU/Web → folder_production_eu_web, with each parent folder as a group too)
/// and by environment (env_production). Names and addresses are validated — the file is written on the control node
/// and anything odd in a name would be a way in — and duplicates are made unique. No secrets: authentication is the
/// control node's own SSH keys / agent.
/// </summary>
public static class AnsibleInventory
{
    public sealed record Entry(HostEntry Host, string Name);
    public sealed record Inventory(string Yaml, List<Entry> Entries);

    private static readonly Regex SafeRx = new(@"^[A-Za-z0-9_][A-Za-z0-9_.-]{0,63}$");

    /// <summary>An inventory name or a group: letters, digits, "_", "." and "-", starting with a letter / digit / "_".</summary>
    public static bool Safe(string s) => SafeRx.IsMatch(s);

    /// <summary>"Production/EU Web" → "production_eu_web".</summary>
    public static string GroupName(string s) => Regex.Replace(s.ToLowerInvariant(), @"[^a-z0-9]+", "_").Trim('_') is { Length: > 0 } g ? g : "ungrouped";

    public static Inventory Build(IEnumerable<HostEntry> hosts)
    {
        var entries = new List<Entry>();
        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var h in hosts.Where(h => h.Protocol == "ssh" && h.Address.Length > 0 && !h.IsAdHoc))
        {
            if (!NetTests.ValidHost(h.Address) || h.Username.Length == 0 || !Regex.IsMatch(h.Username, @"^[A-Za-z0-9_][A-Za-z0-9_.@-]{0,63}$") || h.Port is < 1 or > 65535) continue;
            var name = GroupName(h.Name.Length > 0 ? h.Name : h.Address).Replace('_', '-');
            if (!Safe(name)) name = "host-" + h.Id[..8];
            var unique = name; for (int i = 2; !used.Add(unique); i++) unique = $"{name}-{i}";
            entries.Add(new Entry(h, unique));
        }
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by DarkCipher ServerManagement from saved hosts — no secrets; SSH keys / agent on the control node authenticate.");
        sb.AppendLine("all:");
        sb.AppendLine("  hosts:");
        foreach (var e in entries)
        {
            sb.AppendLine($"    {e.Name}:");
            sb.AppendLine($"      ansible_host: {Y(e.Host.Address)}");
            if (e.Host.Port != 22) sb.AppendLine($"      ansible_port: {e.Host.Port}");
            sb.AppendLine($"      ansible_user: {Y(e.Host.Username)}");
        }
        var groups = new SortedDictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var e in entries)
        {
            var parts = AppData.NormalizeFolder(e.Host.Group).Split('/', StringSplitOptions.RemoveEmptyEntries);
            for (int i = 1; i <= parts.Length; i++) Add(groups, "folder_" + GroupName(string.Join("/", parts.Take(i))), e.Name);
            if (Envs.Normalize(e.Host.Environment) is { Length: > 0 } env) Add(groups, "env_" + GroupName(env), e.Name);
            if (e.Host.Platform is { Length: > 0 } pf) Add(groups, "platform_" + GroupName(pf), e.Name);
        }
        if (groups.Count > 0)
        {
            sb.AppendLine("  children:");
            foreach (var (g, names) in groups)
            {
                sb.AppendLine($"    {g}:");
                sb.AppendLine("      hosts:");
                foreach (var n in names) sb.AppendLine($"        {n}:");
            }
        }
        return new Inventory(sb.ToString(), entries);
    }

    private static void Add(SortedDictionary<string, List<string>> g, string key, string name)
    {
        if (!Safe(key)) return;
        if (!g.TryGetValue(key, out var l)) g[key] = l = new List<string>();
        if (!l.Contains(name)) l.Add(name);
    }

    /// <summary>A YAML scalar: quoted so nothing in it can start a new key or a flow sequence.</summary>
    private static string Y(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
